/* ============================================================
   content.js —— 這個 App 裡「所有給人看的字」都在這個檔
   ============================================================

   要改題目、說明、按鈕上的字，只改這個檔。
   程式在 app.js，樣式在 style.css，平常不用動。

   ■ 改的時候只要記三件事
     1. 只改「引號裡面」的字。引號、逗號、括號、冒號不要刪。
     2. 字裡面的 {n}、{total}、{people} 是程式會自動填的數字，要留著。
     3. 改完用瀏覽器打開 index.html 看一次。畫面全白＝少了逗號或引號。

   ■ 題目（questions）每個欄位的意思
     id          題號。已經填過的答案是照題號存的，所以【不要改、不要重複】。
                 要加新題，用一個沒用過的號碼。
     textLabel   （可以沒有）有選項的題目，下面那個「想多寫一點」輸入框的說明。沒寫就用共用的那一句。
     more        （可以沒有）第二組可以點的選項（可以不選）。寫法：more: { label: '這一組的標題', options: [ ['圖', '字'], … ] }
     layer       'day'＝「怎麼陪他」那一組；'future'＝「以後的事」那一組。
     title       步道上和「怎麼陪我」那一頁顯示的短標題。
     who         'me'＝會出現「可以請他自己回答」；'parent'＝不出現。
     q           題目（完整的問法）。
     short       （可以沒有）短標題，20 個字以內。題目超過 20 個字時才需要：
                 第一個畫面只顯示短標題，下一個畫面才顯示完整的題目。
     hint        題目下面那行小字。
     options     圖卡選項（可以沒有）。每一個是 ['圖示', '文字']。
                 ⚠ 改了選項的文字，先前點過那一個選項的紀錄會對不起來。
     ask         （只有「以後的事」用）還沒想好時顯示的「可以先這樣做」。可以沒有。
     nameFor     （可以沒有）哪幾個選項是「一個人」：選了就在下面出現一格寫他的稱呼，首頁那扇窗會寫上這個稱呼。
     circleShort （和 circleName、nameFor 一起用）窗上第一行的短名字（例如「臨時接手」），第二行是稱呼。
     circleName  （可以沒有）有寫的話，這一題會變成陪伴圈上的一個位置，
                 位置的名字就是這裡寫的字。
     circleFromOptions
                 （可以沒有）寫 true 的話，這一題點選的圖卡會變成家裡一扇淡色的窗。
     answers     （可以沒有）這一題自己的三個答案說法，取代「想好了／想到一半／還沒想」。
                 寫法：answers: { done: '有一個人可以', half: '想得到，還沒開口', none: '現在想不到' }
     why         （可以沒有）收在「為什麼問這個？」裡的一段話，點了才展開。
     notes       （可以沒有）勾了選項之後，每個選項下面有沒有自己的補充格。沒寫＝「怎麼陪他」那幾題有、「以後的事」沒有。
     sub         （只有 kind: 'choice' 用，可以沒有）點了某個選項，同一頁下面接著出現的第二層：
                 { '選項的字': { q: '問什麼', options: ['…', '…'] } } 或 { '選項的字': { text: '輸入框的說明' } }
     kind        （可以沒有）第四版新增的題型。沒寫＝原本那種（先問狀態，再回答）。
                 'choice'＝一個畫面、幾個大按鈕，點一個就記下（2026-11-18 起不自己跳頁，按「下一步」才走）。
                 'people'＝點人物（可以選好幾個），也可以自己打稱呼。
                 這兩種題目的 id 用英文代號（例如 'hisAge'），順序和規則裡就寫這個代號。
     askIf       （可以沒有）符合條件才問。寫法：askIf: [ { of: 'day', is: ['在學校'] } ]
                 好幾條＝每一條都要符合；「符合其中一條就好」寫成 { any: [ {…}, {…} ] }
                 of 寫哪一題的代號（或 'stage' 階段、'help' 需要幫忙的事、'care' 誰照顧），
                 is 寫答案裡要有的字。條件不符合時這一題不會自己跳出來，但「看全部的步驟」裡還是點得到。
     afterCount  （可以沒有）至少答過幾題之後才問（比較重的題目用）。
     chapter     （可以沒有）進度條和「全部的步驟」把這一題算在哪一段。沒寫就和 layer 一樣。
                 只影響「顯示在哪一段」，不影響列印頁和家的窗。

   ■ 題目的順序和分支（flow）——第四版新增
     參賽者之後要調「答了什麼 → 下一題問什麼」，只改這裡，不用動程式。
     代號   每一題有一個代號：'q7'＝題號 7 的那一題；'now'＝他現在的狀況；
            'others'＝還有誰在陪他；'worry'＝最常想到哪一件；'res'＝可以找誰那一頁；
            第四版新增的題目直接用它的英文 id（'hisAge'、'day'…）。
     order  沒有特別規則時，照這個順序一題一題問（代號的清單）。
     origin／worry 的 options
            每個選項的 go 寫「選了這個，下一題去哪」（寫代號）。
     題目（questions）也可以加 next：
            next: 'q1'                        答完一律接到題號 1
            next: [ { when: 'done', go: 'q1' },    狀態是「想好了」接題號 1
                    { when: '還不知道', go: 'q9' } ] 點了「還不知道」這張圖卡接題號 9
            when 可以寫狀態（'done' 想好了／'half' 想到一半／'none' 還沒想）或圖卡上的字。
            要去的那一題已經答過或略過時，規則不算數，改照 order 找下一題。

   ■ 資源路線圖（resources.items）
     id     每一列自己的代號。老師填的本地窗口是照代號存的，【不要改、不要重複】。
     stage  人生階段（同一階段的會排在一起，照這裡的順序）。
     when   遇到什麼事。
     ask    可以問誰。🔴 只寫「哪一類服務／哪一種窗口」，不放機構名單。

   🔴 比賽規定：這個檔（含註解）不可以出現姓名、學校、縣市、帳號、email。
   ============================================================ */

